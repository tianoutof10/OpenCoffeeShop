// Generates src/styles/nordicAccents.css: every Bestpresso declaration that uses
// its green accent, remapped to the Nordic neutral palette (paper on charcoal) and scoped to
// [data-theme="nordic"]. Re-run after upstream CSS changes:
//   node scripts/nordic-accents.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const sources = ['src/styles/index.css', 'src/styles/cardSurfaces.css', 'src/styles/settingsLayout.css', 'src/styles/homeAnimations.css', 'src/components/Sidebar/sidebarNavigation.css', 'src/features/machine/drinkUtilityCards.css', 'src/features/insights/insights.css']

// Green accent → paper white; dark greens → neutral greys. Chart colours are handled by tokens in nordic.css, not here.
const hexMap = { '3dc078': 'efeeea', '53d68e': 'efeeea', '70d99f': 'f5f4f1', '72d9a5': 'f5f4f1', '82eac8': 'f5f4f1', 'b9ffda': 'ffffff', '324c3e': '2c2c2c', '14784e': '5a5a58', '26794e': '5a5a58', '42a582': 'efeeea' }
const rgbMap = { '61,192,120': '239,238,234', '83,214,142': '239,238,234', '66,197,153': '239,238,234', '114,217,165': '245,244,241', '130,234,200': '245,244,241', '36,91,60': '60,60,58', '50,76,62': '44,44,44' }
const greenPattern = new RegExp(`#(?:${Object.keys(hexMap).join('|')})\\b|rgba?\\(\\s*(?:${Object.keys(rgbMap).map(key => key.split(',').join('\\s*,\\s*')).join('|')})`, 'i')

function remap(value) {
  let next = value.replace(/#([0-9a-f]{6})\b/gi, (match, hex) => hexMap[hex.toLowerCase()] ? `#${hexMap[hex.toLowerCase()]}` : match)
  next = next.replace(/rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)/gi, (match, r, g, b) => {
    const mapped = rgbMap[`${r},${g},${b}`]
    return mapped ? match.replace(`${r}`, 'R').replace(/R\s*,\s*\d+\s*,\s*\d+/, mapped) : match
  })
  return next
}

/** Minimal CSS walker: yields { prelude, body } for style rules, recursing into @media/@supports. */
function* rules(css, wrappers = []) {
  let index = 0
  while (index < css.length) {
    const open = css.indexOf('{', index)
    if (open < 0) return
    const prelude = css.slice(index, open).replace(/\/\*[\s\S]*?\*\//g, '').trim()
    let depth = 1, cursor = open + 1
    while (cursor < css.length && depth) { if (css[cursor] === '{') depth++; else if (css[cursor] === '}') depth--; cursor++ }
    const body = css.slice(open + 1, cursor - 1)
    if (/^@(media|supports)/.test(prelude)) yield* rules(body, [...wrappers, prelude])
    else if (!prelude.startsWith('@')) yield { prelude, body, wrappers }
    index = cursor
  }
}

const scope = selector => {
  const trimmed = selector.trim()
  if (/\[data-theme=/.test(trimmed)) return null
  if (/^:root\b/.test(trimmed)) return trimmed.replace(/^:root/, ':root[data-theme="nordic"]')
  if (/^(html|body)\b/.test(trimmed)) return trimmed.replace(/^(html|body)/, '$1[data-theme="nordic"]')
  return `[data-theme="nordic"] ${trimmed}`
}

const output = []
for (const source of sources) {
  const css = readFileSync(join(root, source), 'utf8')
  for (const { prelude, body, wrappers } of rules(css)) {
    if (!greenPattern.test(body)) continue
    const declarations = body.split(/;(?![^(]*\))/).map(part => part.trim()).filter(part => part && greenPattern.test(part)).map(remap)
    const selectors = prelude.split(/,(?![^(]*\))/).map(scope).filter(Boolean)
    if (!declarations.length || !selectors.length) continue
    const rule = `${selectors.join(',')}{${declarations.join(';')}}`
    output.push(wrappers.reduceRight((inner, wrapper) => `${wrapper}{${inner}}`, rule))
  }
}
writeFileSync(join(root, 'src/styles/nordicAccents.css'), `/* Generated by scripts/nordic-accents.mjs — do not edit by hand. Bestpresso green accents remapped to the Nordic neutral palette. */\n${output.join('\n')}\n`)
console.log(`nordicAccents.css: ${output.length} rules`)
